export function getTopicLessons(topicId: string): TopicLesson[] {
  return lessonsByTopic[topicId] ?? [];
}

export function getTopicLesson(
  topicId: string,
  lessonSlug: string,
): TopicLesson | undefined {
  return getTopicLessons(topicId).find((lesson) => lesson.slug === lessonSlug);
}

export function getTopicLessonMinutes(topicId: string): number {
  return getTopicLessons(topicId).reduce(
    (total, lesson) => total + lesson.estimatedMinutes,
    0,
  );
}
